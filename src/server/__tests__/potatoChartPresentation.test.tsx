import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createElement} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {load} from 'cheerio';
import {PotatoProductionChartView} from '../../components/PotatoProductionChart';
import {PotatoBenchmarkDisplay,potatoEurKrwRate} from '../../components/PotatoBenchmarkValue';
import {parseDatedDisplayFx} from '../../utils/soybeanPriceSnapshot';
import {chartValueBounds,chartSmoothPath} from '../../components/CommodityChartPresentation';
const snapshot=JSON.parse(fs.readFileSync('.rms-price-history/potato-production-regions-v2.json','utf8'));
const $=load(renderToStaticMarkup(createElement(PotatoProductionChartView,{snapshot})));
assert.equal($('stop').first().attr('stop-opacity'),'0.15');
assert.equal($('stop').last().attr('stop-opacity'),'0.0');
assert.equal($('[data-production-area]').length,1);
assert.equal($('[data-production-area]').attr('data-last-actual-year'),'2025');
assert.equal($('[data-production-line][stroke-dasharray="5 4"]').length,3);
assert.deepEqual($('[data-summary]').map((_,e)=>$(e).attr('data-summary')).get(),['DE','NL','DK']);
assert($('[data-summary]').toArray().every(e=>$(e).attr('class')?.includes('bg-[#fafbfc]')));
assert.equal($('[data-chart-axis-label]').length,4);
for(const text of ['전체 원료감자(종자용 포함)','동적 공통','누락값 연결','Retained original','EU27'])assert(!$.text().includes(text));
assert.deepEqual(chartValueBounds([100,200]),{low:92,high:208});
assert.equal(chartSmoothPath([{x:0,y:25},{x:500,y:125}]),'M 0,25 C 250,25 250,125 500,125');
// Synthetic FX packet tests: same dated USD base, no currency movements in underlying quote.
const fx=parseDatedDisplayFx({base:'USD',date:'2026-10-20',rates:{KRW:1400,EUR:.8}},'2026-10-21T00:00:00Z')!;
assert.equal(potatoEurKrwRate(fx),1750);assert.equal(potatoEurKrwRate(null),null);
assert.equal(potatoEurKrwRate({...fx,EUR_USD:NaN}),null);
assert.equal(potatoEurKrwRate({...fx,observationDate:'2026-10-22'}),null);
const quote={data:{eurPerMT:100,period:'2026-08'},verifiedAt:'2026-10-20'} as any;
const converted=renderToStaticMarkup(createElement(PotatoBenchmarkDisplay,{quote,fx}));
for(const text of ['175,000','/MT'])assert(converted.includes(text));for(const text of ['data-potato-fx','적용 환율','EUR 기준'])assert(!converted.includes(text));
const usd=renderToStaticMarkup(createElement(PotatoBenchmarkDisplay,{quote,fx,currency:'USD'}));assert(usd.includes('$125.00')&&usd.includes('/MT')&&!usd.includes('USD/MT'));const eur=renderToStaticMarkup(createElement(PotatoBenchmarkDisplay,{quote,fx,currency:'EUR'}));assert(eur.includes('€100.00')&&eur.includes('/MT')&&!eur.includes('EUR/MT'));
const fallback=renderToStaticMarkup(createElement(PotatoBenchmarkDisplay,{quote}));assert(fallback.includes('100.00'));assert(!fallback.includes('KRW/MT'));
assert.equal(quote.data.eurPerMT,100);
console.log('PASS shared Wheat geometry/presentation, actual-only gradient, three retained estimates, dated FX cross-rate, provenance and EUR fallback');
