import {strict as assert} from 'node:assert';
import {parseKcciTimeseries} from '../kcciTimeseriesParser.ts';
import {kcciNeedsWeeklyFetch} from '../kcciScraperService.ts';
const now=new Date('2026-11-14T00:00:00Z');
const example=(a='1,234',b='1,222')=>`<html><head><title>KOBC Container Composite Index</title></head><body><h1>KCCI 컨테이너선운임지수</h1><table><thead><tr><th>Date</th><th>KCCI</th><th>Other lane</th></tr></thead><tbody><tr><td>2026-11-09</td><td>${a}</td><td>99</td></tr><tr><td>2026-11-02</td><td>${b}</td><td>98</td></tr></tbody></table></body></html>`;
const a=parseKcciTimeseries(example(),now);
assert.equal(a.kcciPoints,1234);assert.equal(a.previousPoints,1222);
assert.equal(a.observationDate,'2026-11-09');assert.equal(a.previousObservationDate,'2026-11-02');
assert.equal(a.history.length,2);
assert.throws(()=>parseKcciTimeseries(example().replaceAll('KCCI','CCFI'),now));
assert.throws(()=>parseKcciTimeseries(example().replace('2026-11-09','2026-11-31'),now));
assert.throws(()=>parseKcciTimeseries(example().replace('2026-11-09','2026-11-16'),now));
assert.throws(()=>parseKcciTimeseries(example().replace('1,234','N/A'),now));
assert.throws(()=>parseKcciTimeseries(example().replace('2026-11-09','2026-11-02').replace('1,234','1,888'),now));
assert.throws(()=>parseKcciTimeseries(example().replace('Date','Week'),now));
const prior={observationDate:'2026-11-02'} as Parameters<typeof kcciNeedsWeeklyFetch>[0];
assert.equal(kcciNeedsWeeklyFetch(prior,new Date('2026-11-09T00:00:00Z')),false,'Monday 09 KST should not call before release');
assert.equal(kcciNeedsWeeklyFetch(prior,new Date('2026-11-10T00:00:00Z')),true,'Tuesday 09 KST should check');
assert.equal(kcciNeedsWeeklyFetch({...prior,observationDate:'2026-11-09'},new Date('2026-11-11T00:00:00Z')),false,'current week should skip network');
console.log('PASS: official KCCI composite identity, two dated rows, change, invalid/CCFI/future/conflict rejection, Tuesday schedule');
